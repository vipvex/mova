(async () => {
  // 1. List all users with all their progress
  const allUsers = await db.select().from(users);
  console.log("=== All users + their learned-word counts ===");
  for (const u of allUsers) {
    const learned = await db
      .select({ word: vocabulary.targetWord, lang: vocabulary.language })
      .from(learningProgress)
      .innerJoin(vocabulary, eq(learningProgress.wordId, vocabulary.id))
      .where(and(eq(learningProgress.userId, u.id), eq(learningProgress.isLearned, true)));
    const byLang: Record<string, number> = {};
    for (const r of learned) byLang[r.lang] = (byLang[r.lang] || 0) + 1;
    const langStr = Object.entries(byLang).map(([l, c]) => `${l}=${c}`).join(", ");
    console.log(`  ${u.username.padEnd(20)} (lang=${u.language}) → ${learned.length} learned [${langStr || "—"}]`);
  }

  console.log("\n=== Per-user curriculum coverage ===\n");

  for (const target of allUsers) {
    // Pull all Russian words this user has marked as learned
    const learned = await db
      .select({ word: vocabulary.targetWord })
      .from(learningProgress)
      .innerJoin(vocabulary, eq(learningProgress.wordId, vocabulary.id))
      .where(and(
        eq(learningProgress.userId, target.id),
        eq(learningProgress.isLearned, true),
        eq(vocabulary.language, "russian"),
      ));

    const learnedSet = new Set(learned.map((r) => r.word.toLowerCase().trim()));
    console.log(`--- ${target.username} (${learnedSet.size} Russian words learned) ---`);
    if (learnedSet.size === 0) {
      console.log("  (no Russian progress)\n");
      continue;
    }

    // Per-phase coverage
    const allCurriculum = new Set<string>();
    for (const [phase, list] of Object.entries(CURRICULUM_500)) {
      const uniqList = [...new Set(list.map((w) => w.toLowerCase().trim()))];
      let known = 0;
      const knownWords: string[] = [];
      for (const w of uniqList) {
        allCurriculum.add(w);
        if (learnedSet.has(w)) {
          known++;
          knownWords.push(w);
        }
      }
      const pct = ((known / uniqList.length) * 100).toFixed(1);
      console.log(`  ${phase.padEnd(45)} ${String(known).padStart(3)}/${String(uniqList.length).padStart(3)} = ${pct.padStart(5)}%`);
      if (knownWords.length > 0 && knownWords.length <= 30) {
        console.log(`    known: ${knownWords.join(", ")}`);
      }
    }

    const totalKnown = [...allCurriculum].filter((w) => learnedSet.has(w)).length;
    const totalCurriculum = allCurriculum.size;
    const totalPct = ((totalKnown / totalCurriculum) * 100).toFixed(1);
    console.log(`  TOTAL: ${totalKnown}/${totalCurriculum} = ${totalPct}%`);

    const outsideCurriculum = [...learnedSet].filter((w) => !allCurriculum.has(w));
    console.log(`  Learned outside the 500: ${outsideCurriculum.length}`);
    if (outsideCurriculum.length > 0 && outsideCurriculum.length <= 30) {
      console.log(`    ${outsideCurriculum.join(", ")}`);
    }
    console.log("");
  }

  process.exit(0);
})();
