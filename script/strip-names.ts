const NAME_SET = new Set([
  ...FIRST_NAMES_M,
  ...FIRST_NAMES_F,
  ...SURNAMES,
  ...CITIES_PLACES,
].map((s) => s.toLowerCase().trim()));

// Suffix patterns for surnames + patronymics + place adjectives
const SUFFIX_PATTERNS: RegExp[] = [
  /(ович|евич)$/,       // patronymic male: Иванович, Сергеевич
  /(овна|евна|ична)$/,  // patronymic female: Ивановна, Сергеевна
  /(ский|ская|ское|ские|цкий|цкая)$/, // adjective from place: московский, парижский (but ALSO general adj like русский — careful)
];

// Words to NOT reject even if they match a suffix pattern (false positives that are actual vocabulary)
const EXCEPTIONS = new Set([
  "русский","русская","русские", // these are ambiguous (Russian language/people) — keep as adjectives
  "детский","детская","детское", // childlike — common adjective
  "женский","женская","мужской","мужская", // gender adjectives
  "взрослый","взрослая",
  "большой","больший",
  "маленький","маленькая",
  "горький","сладкий","громкий","ловкий","низкий","узкий","робкий",
  "близкий","далекий","далёкий","высокий","глубокий","широкий","редкий","жидкий","гладкий","мягкий","твёрдый","тяжёлый",
  "красивый","некрасивый",
  "русская", // in case "russian language/woman"
  "английский","французский","немецкий","итальянский","испанский","китайский","японский", // languages — keep as adj
  "царский","богатырский","богатый","нищий","добрый","злой","скользкий","липкий","шёлковый",
  "сосиски",
]);

(async () => {
  const all = await db
    .select({ id: frequencyDictionary.id, word: frequencyDictionary.word, tier: frequencyDictionary.tier })
    .from(frequencyDictionary)
    .where(and(eq(frequencyDictionary.language, "russian"), inArray(frequencyDictionary.tier, ["T1", "T2", "T3", "T4"])));

  console.log(`Scanning ${all.length} T1-T4 words...`);

  const flagged: { id: string; word: string; tier: string | null; why: string }[] = [];

  for (const w of all) {
    const word = w.word.toLowerCase().trim();
    if (EXCEPTIONS.has(word)) continue;

    if (NAME_SET.has(word)) {
      flagged.push({ ...w, why: "name-list" });
      continue;
    }

    for (const pat of SUFFIX_PATTERNS) {
      if (pat.test(word)) {
        flagged.push({ ...w, why: "suffix:" + word.match(pat)?.[0] });
        break;
      }
    }
  }

  console.log(`Flagged ${flagged.length} proper nouns to demote.`);
  console.log("\nBy tier:");
  const byTier: Record<string, number> = {};
  for (const f of flagged) byTier[f.tier ?? "?"] = (byTier[f.tier ?? "?"] || 0) + 1;
  console.table(byTier);

  console.log("\nFirst 60 flagged samples:");
  console.log(flagged.slice(0, 60).map((f) => `${f.word}(${f.tier}/${f.why})`).join(", "));

  if (flagged.length > 0) {
    const ids = flagged.map((f) => f.id);
    const r = await db
      .update(frequencyDictionary)
      .set({
        tier: "Reject",
        gatePass: false,
        gateReason: "proper-noun",
        rationale: sql`COALESCE(${frequencyDictionary.rationale}, '') || ' [demoted: name strip]'`,
      })
      .where(inArray(frequencyDictionary.id, ids));
    console.log(`\nDemoted ${r.rowCount} rows → Reject.`);
  }

  process.exit(0);
})();
